"""Render the public-corpus benchmark results as a Markdown report.

Reads ``corpus/results/<profile>.json`` and prints a BENCHMARK.md-style
section: per-file table, aggregate byte sum, per-file mean, worst case, and
win count. With ``--write`` the section is spliced into BENCHMARK.md between
the ``PUBLIC-CORPUS`` markers, so refreshing the published numbers is a
single command after new results land.

Usage:
    python corpus/report.py                  # print the lite section
    python corpus/report.py --write          # splice into BENCHMARK.md
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

CORPUS_DIR = Path(__file__).resolve().parent
REPO_ROOT = CORPUS_DIR.parent
RESULTS_DIR = CORPUS_DIR / "results"
BENCHMARK_PATH = REPO_ROOT / "BENCHMARK.md"

BEGIN_MARKER = "<!-- PUBLIC-CORPUS:BEGIN -->"
END_MARKER = "<!-- PUBLIC-CORPUS:END -->"


def render_section(results: list[dict], profile: str) -> str:
    ok = [r for r in results if "error" not in r and r["blc1"]["roundtrip_ok"]]
    failed = [r for r in results if "error" in r]
    lines = [
        BEGIN_MARKER,
        "",
        f"## Public corpus ({profile} profile)",
        "",
        "Every file below is fetched and hash-verified by `corpus/fetch.py` from",
        "pinned upstream releases; see `corpus/manifest.json` for versions,",
        "licenses, and toolchain evidence. Baseline: 7-Zip 26.06 with",
        "`7z a -t7z -mx=9 -m0=BCJ -m1=LZMA2`. Every BLC1 archive was decoded",
        "and matched byte-for-byte against its input.",
        "",
    ]
    if not ok:
        lines.append("No completed results yet.")
    else:
        lines += [
            "| Entry | Track | Compiler | Input bytes | BLC1 | 7-Zip | BLC1 delta |",
            "|---|---|---|---:|---:|---:|---:|",
        ]
        manifest = {
            e["id"]: e
            for e in json.loads(
                (CORPUS_DIR / "manifest.json").read_text(encoding="utf-8")
            )["entries"]
        }
        for r in sorted(ok, key=lambda r: r["input_size"]):
            entry = manifest[r["id"]]
            lines.append(
                f"| {entry['project']} {entry['version']} | {r['track']} "
                f"| {entry['compiler']} | {r['input_size']:,} "
                f"| {r['blc1']['size']:,} | {r['seven_zip']['size']:,} "
                f"| {r['delta_pct']:+.3f}% |"
            )
        total_in = sum(r["input_size"] for r in ok)
        total_blc1 = sum(r["blc1"]["size"] for r in ok)
        total_7z = sum(r["seven_zip"]["size"] for r in ok)
        aggregate = (total_blc1 - total_7z) / total_7z * 100
        mean = sum(r["delta_pct"] for r in ok) / len(ok)
        worst = max(ok, key=lambda r: r["delta_pct"])
        best = min(ok, key=lambda r: r["delta_pct"])
        wins = sum(1 for r in ok if r["delta_pct"] < 0)
        lines += [
            f"| **Total** | mixed | mixed | **{total_in:,}** "
            f"| **{total_blc1:,}** | **{total_7z:,}** | **{aggregate:+.3f}%** |",
            "",
            f"BLC1 is smaller on {wins} of {len(ok)} samples. "
            f"Mean per-file delta: {mean:+.3f}%. "
            f"Worst case: {worst['id']} at {worst['delta_pct']:+.3f}%; "
            f"best case: {best['id']} at {best['delta_pct']:+.3f}%.",
            "",
        ]
        total_encode = sum(r["blc1"]["encode_seconds"] for r in ok)
        total_7z_encode = sum(r["seven_zip"]["encode_seconds"] for r in ok)
        lines += [
            f"Encoder wall time (research prototype, preset 9): BLC1 "
            f"{total_encode:.0f}s total vs 7-Zip {total_7z_encode:.1f}s. "
            "Speed is not yet a published metric; see limitations.",
            "",
        ]
    if failed:
        lines.append("Failed entries (excluded from the table):")
        for r in failed:
            lines.append(f"- {r['id']}: {r['error']}")
        lines.append("")
    lines += [
        "Entries absent from this table are pending an encoder run; the",
        "section is regenerated by `corpus/report.py --write`.",
        "",
        END_MARKER,
    ]
    return "\n".join(lines)


def splice(section: str) -> None:
    text = BENCHMARK_PATH.read_text(encoding="utf-8")
    if BEGIN_MARKER in text and END_MARKER in text:
        head = text.split(BEGIN_MARKER)[0]
        tail = text.split(END_MARKER, 1)[1]
        updated = head + section + tail
    else:
        updated = text.rstrip() + "\n\n" + section + "\n"
    BENCHMARK_PATH.write_text(updated, encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--profile", default="lite", choices=["lite", "full"])
    parser.add_argument("--write", action="store_true", help="splice into BENCHMARK.md")
    args = parser.parse_args()

    results_path = RESULTS_DIR / f"{args.profile}.json"
    if not results_path.exists():
        print(f"no results file: {results_path}", file=sys.stderr)
        return 1
    results = json.loads(results_path.read_text(encoding="utf-8"))
    section = render_section(results, args.profile)
    if args.write:
        splice(section)
        print(f"updated {BENCHMARK_PATH}")
    else:
        print(section)
    return 0


if __name__ == "__main__":
    sys.exit(main())
